const mongoose = require("mongoose");

const palaceSchema = new mongoose.Schema({
    owner:{
        type:mongoose.Schema.Types.ObjectId,
        ref:"User",
        required:true
    },
    Images:[{
        type:String,
        required:true
    }],
    name:{
        type:String,
        required:true,
        trim:true
    },
    location:{
        type:String,
        required:true,
        trim:true
    },
    description:{
        type:String,
        required:true
    },
    price:{
        type:Number,
        required:true,
        min:0
    },
    capacity:{
        type:Number,
        required:true,
        min:1
    },
    facilities:[{type:String}],
    isAvailable:{
        type:Boolean,
        default:true
    },
    status:{
        type:String,
        enum:["pending","approved","rejected"],
        default:"pending",
    }
},{
    timestamps:true
})
module.exports = mongoose.model("Palace",palaceSchema) ; 